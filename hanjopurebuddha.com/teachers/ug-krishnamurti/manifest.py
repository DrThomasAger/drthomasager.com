"""Write download-manifest.json and fetch.sh from items.json.

Every item whose URL points at something a machine can pull down (an
archive.org item, a YouTube video or playlist, a SoundCloud track, a
Wikisource page, a PDF, a WELL page) becomes one line of fetch.sh, grouped
by tool. Run fetch.sh on a machine that can reach those hosts:

    pip install internetarchive yt-dlp
    bash fetch.sh            # downloads into ./downloads/<medium>/

Nothing here is downloaded by the build; the site links out.
"""
import json
import pathlib
import re
from urllib.parse import urlparse, parse_qs

HERE = pathlib.Path(__file__).resolve().parent
items = json.loads((HERE / "items.json").read_text(encoding="utf-8"))
meta = json.loads((HERE / "meta.json").read_text(encoding="utf-8")) if (HERE / "meta.json").exists() else {}
if meta.get("fetch") is False:
    (HERE / "download-manifest.json").write_text(json.dumps({"fetch": False, "note": meta.get("fetch_note", "")}, ensure_ascii=False, indent=1), encoding="utf-8")
    (HERE / "fetch.sh").write_text("#!/usr/bin/env bash\n# No downloads for this teacher.\n# " + (meta.get("fetch_note") or "") + "\n", encoding="utf-8")
    print("fetch disabled for this teacher"); raise SystemExit(0)

groups = {"archive_org": [], "youtube": [], "soundcloud": [], "wikisource": [], "pdf": [], "well": [], "other_pages": []}
seen = set()
for it in items:
    u = it.get("url")
    if not u or u in seen:
        continue
    seen.add(u)
    p = urlparse(u)
    host = p.netloc.lower().replace("www.", "")
    rec = {"id": it["id"], "title": it["title"], "medium": it["medium"], "url": u}
    if host == "archive.org" and p.path.startswith("/details/"):
        rec["identifier"] = p.path.split("/")[2]
        groups["archive_org"].append(rec)
    elif host in ("youtube.com", "m.youtube.com", "youtu.be"):
        q = parse_qs(p.query)
        rec["video_id"] = (q.get("v") or [None])[0] or (p.path.strip("/") if host == "youtu.be" else None)
        rec["playlist_id"] = (q.get("list") or [None])[0]
        groups["youtube"].append(rec)
    elif host == "soundcloud.com":
        groups["soundcloud"].append(rec)
    elif host.endswith("wikisource.org"):
        rec["raw_url"] = u.split("#")[0] + ("&" if "?" in u else "?") + "action=raw" if "/wiki/" in u else u
        rec["raw_url"] = re.sub(r"/wiki/([^?]+)\?action=raw", lambda m: "/w/index.php?title=" + m.group(1) + "&action=raw", rec["raw_url"])
        groups["wikisource"].append(rec)
    elif u.lower().endswith(".pdf"):
        groups["pdf"].append(rec)
    elif host in ("people.well.com", "well.com"):
        groups["well"].append(rec)
    else:
        groups["other_pages"].append(rec)

(HERE / "download-manifest.json").write_text(json.dumps(groups, ensure_ascii=False, indent=1), encoding="utf-8")

lines = ["#!/usr/bin/env bash", "# Generated by manifest.py from items.json. Pulls every machine-fetchable item.",
         "# Resumable: every tool below skips what is already on disk. Re-run freely.",
         "set -u", "mkdir -p downloads/{archive_org,youtube,soundcloud,wikisource,pdf,well,pages}",
         "log() { printf '%s\t%s\n' \"$(date -u +%FT%TZ)\" \"$*\" >> downloads/fetch.log; }", ""]
lines.append("# --- archive.org items (pip install internetarchive)")
for r in groups["archive_org"]:
    lines.append(f"ia download {r['identifier']} --destdir downloads/archive_org --no-change-timestamp --retries 3 && log ok {r['identifier']} || log fail {r['identifier']}  # {r['title'][:70]}")
lines.append("\n# --- YouTube (pip install yt-dlp); --download-archive makes this resumable")
for r in groups["youtube"]:
    if r.get("video_id"):
        lines.append(f"yt-dlp --download-archive downloads/youtube/.archive -o 'downloads/youtube/%(title)s [%(id)s].%(ext)s' --write-info-json --write-subs --write-auto-subs 'https://www.youtube.com/watch?v={r['video_id']}'  # {r['title'][:60]}")
    elif r.get("playlist_id"):
        lines.append(f"yt-dlp --download-archive downloads/youtube/.archive -o 'downloads/youtube/%(playlist)s/%(title)s [%(id)s].%(ext)s' --write-info-json 'https://www.youtube.com/playlist?list={r['playlist_id']}'  # {r['title'][:60]}")
    else:
        lines.append(f"yt-dlp --download-archive downloads/youtube/.archive -o 'downloads/youtube/%(uploader)s/%(title)s [%(id)s].%(ext)s' --write-info-json '{r['url']}'  # {r['title'][:60]}")
lines.append("\n# --- SoundCloud (yt-dlp)")
for r in groups["soundcloud"]:
    lines.append(f"yt-dlp --download-archive downloads/soundcloud/.archive -o 'downloads/soundcloud/%(uploader)s/%(title)s.%(ext)s' '{r['url']}'  # {r['title'][:60]}")
lines.append("\n# --- Wikisource full texts (wikitext)")
for r in groups["wikisource"]:
    name = re.sub(r"[^A-Za-z0-9._-]+", "_", r["url"].split("/wiki/")[-1])[:120] if "/wiki/" in r["url"] else r["id"]
    lines.append(f"[ -s 'downloads/wikisource/{name}.wiki' ] || curl -sSL '{r['raw_url']}' -o 'downloads/wikisource/{name}.wiki'  # {r['title'][:60]}")
lines.append("\n# --- PDFs")
for r in groups["pdf"]:
    lines.append(f"wget -q -nc -P downloads/pdf '{r['url']}'  # {r['title'][:60]}")
lines.append("\n# --- The WELL pages")
for r in groups["well"]:
    lines.append(f"wget -q -nc -P downloads/well '{r['url']}'  # {r['title'][:60]}")
lines.append("\n# --- Other pages (HTML snapshots)")
for r in groups["other_pages"]:
    lines.append(f"wget -q -nc -E -P downloads/pages '{r['url']}'  # {r['title'][:60]}")
(HERE / "fetch.sh").write_text("\n".join(lines) + "\n", encoding="utf-8")
print({k: len(v) for k, v in groups.items()})
